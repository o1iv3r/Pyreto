"""Tests for fit_references (port of R's Fit_References) and the LP tower it uses."""

from __future__ import annotations

import warnings

import numpy as np
import pytest

from pyreto import PGPModel, PPPModel, excess_frequency, fit_references, layer_mean
from pyreto.matching import _calculate_layer_losses

# Example from the R documentation of Fit_References.
COVERS = np.array([1000.0, 1000.0, 1000.0])
ATT = np.array([1000.0, 2000.0, 5000.0])
EL = np.array([100.0, 50.0, 10.0])
THR = np.array([4000.0, 10000.0])
FQS = np.array([0.04, 0.005])


class TestPiecewisePareto:
    def test_matches_all_references(self) -> None:
        fit = fit_references(COVERS, ATT, EL, THR, FQS)
        assert isinstance(fit, PPPModel)
        assert fit.status == 0
        assert fit.is_valid()
        assert fit.t[0] == 1000.0
        np.testing.assert_allclose(layer_mean(fit, COVERS, ATT), EL, rtol=1e-6)
        np.testing.assert_allclose(excess_frequency(fit, THR), FQS, rtol=1e-6)

    def test_overlapping_layers_use_lp_tower(self) -> None:
        covers = np.array([2000.0, 2000.0, 1000.0])
        att = np.array([1000.0, 2000.0, 5000.0])
        el = np.array([600.0, 350.0, 30.0])
        fit = fit_references(covers, att, el)
        assert fit.status == 0
        np.testing.assert_allclose(layer_mean(fit, covers, att), el, rtol=1e-6)

    def test_threshold_inside_layer_is_overlapping(self) -> None:
        thr = np.array([1500.0, 6000.0])
        fqs = np.array([0.08, 0.004])
        fit = fit_references(COVERS, ATT, EL, thr, fqs)
        assert fit.status == 0
        np.testing.assert_allclose(layer_mean(fit, COVERS, ATT), EL, rtol=1e-6)
        np.testing.assert_allclose(excess_frequency(fit, thr), fqs, rtol=1e-6)

    def test_model_threshold_below_references(self) -> None:
        fit = fit_references(COVERS, ATT, EL, THR, FQS, model_threshold=500.0)
        assert fit.t[0] == 500.0
        np.testing.assert_allclose(layer_mean(fit, COVERS, ATT), EL, rtol=1e-6)
        np.testing.assert_allclose(excess_frequency(fit, THR), FQS, rtol=1e-6)

    def test_dispersion_is_kept(self) -> None:
        assert fit_references(COVERS, ATT, EL, THR, FQS, dispersion=2.0).dispersion == 2.0

    def test_inconsistent_references_fail(self) -> None:
        # RoL of the second layer exceeds that of the first.
        el = np.array([100.0, 150.0, 20.0])
        with pytest.warns(UserWarning, match="inconsistent"):
            fit = fit_references(COVERS, np.array([1000.0, 2000.0, 3000.0]), el)
        assert fit.status == 2

    def test_inconsistent_references_ignored(self) -> None:
        att = np.array([1000.0, 2000.0, 3000.0])
        el = np.array([100.0, 150.0, 20.0])
        with pytest.warns(UserWarning, match="Some data has been ignored"):
            fit = fit_references(COVERS, att, el, ignore_inconsistent_references=True)
        assert fit.status == 1
        # The first and third layers are kept, the second is dropped.
        np.testing.assert_allclose(layer_mean(fit, COVERS, att)[[0, 2]], el[[0, 2]], rtol=1e-6)


class TestSmallCases:
    def test_single_layer_uses_default_alpha(self) -> None:
        fit = fit_references([1000.0], [1000.0], [100.0], default_alpha=2.5)
        assert fit.alpha[0] == 2.5
        np.testing.assert_allclose(layer_mean(fit, 1000.0, 1000.0), 100.0)

    def test_single_threshold(self) -> None:
        fit = fit_references(thresholds=[2000.0], frequencies=[0.1], model_threshold=1000.0)
        np.testing.assert_allclose(excess_frequency(fit, 2000.0), 0.1)
        np.testing.assert_allclose(fit.fq, 0.1 * 2.0**2)

    def test_two_layers(self) -> None:
        fit = fit_references([1000.0, 1000.0], [1000.0, 2000.0], [100.0, 50.0])
        assert len(fit.alpha) == 1
        np.testing.assert_allclose(
            layer_mean(fit, np.array([1000.0, 1000.0]), np.array([1000.0, 2000.0])),
            [100.0, 50.0],
        )

    def test_gen_pareto_small_case_has_equal_alphas(self) -> None:
        fit = fit_references(
            [1000.0, 1000.0], [1000.0, 2000.0], [100.0, 50.0], severity_distribution="GenPareto"
        )
        assert isinstance(fit, PGPModel)
        assert fit.alpha_ini == fit.alpha_tail


class TestLeastSquares:
    def test_pareto_returns_single_piece(self) -> None:
        fit = fit_references(COVERS, ATT, EL, THR, FQS, severity_distribution="Pareto")
        assert isinstance(fit, PPPModel)
        assert fit.status == 0
        assert len(fit.alpha) == 1
        # A single Pareto cannot match five references, but it should be close.
        np.testing.assert_allclose(layer_mean(fit, COVERS, ATT), EL, rtol=0.3)

    def test_pareto_recovers_exact_pareto(self) -> None:
        # References generated by FQ=0.5, alpha=1.7 above 1000.
        truth = PPPModel(fq=0.5, t=np.array([1000.0]), alpha=np.array([1.7]))
        thr = np.array([3000.0, 8000.0])
        fit = fit_references(
            COVERS,
            ATT,
            layer_mean(truth, COVERS, ATT),
            thr,
            excess_frequency(truth, thr),
            severity_distribution="Pareto",
        )
        assert fit.fq == pytest.approx(0.5, rel=1e-3)
        assert fit.alpha[0] == pytest.approx(1.7, rel=1e-3)

    def test_gen_pareto(self) -> None:
        fit = fit_references(COVERS, ATT, EL, severity_distribution="GenPareto")
        assert isinstance(fit, PGPModel)
        assert fit.status == 0
        np.testing.assert_allclose(layer_mean(fit, COVERS, ATT), EL, rtol=1e-3)


class TestValidation:
    @pytest.mark.parametrize(
        ("kwargs", "message"),
        [
            ({"severity_distribution": "Lognormal"}, "severity_distribution"),
            ({"dispersion": 0.0}, "Dispersion"),
            ({"model_threshold": 2000.0}, "model_threshold"),
            ({"default_alpha": 1.0}, "default_alpha"),
            ({"frequencies": [0.1]}, "same length"),
        ],
    )
    def test_invalid_input(self, kwargs: dict, message: str) -> None:
        args = {
            "covers": COVERS,
            "attachment_points": ATT,
            "expected_layer_losses": EL,
            "thresholds": THR,
            "frequencies": FQS,
            **kwargs,
        }
        with pytest.warns(UserWarning, match=message):
            fit = fit_references(**args)
        assert fit.status == 2

    def test_no_references(self) -> None:
        with pytest.warns(UserWarning, match="must be positive"):
            assert fit_references().status == 2


class TestCalculateLayerLosses:
    def test_overlapping_inconsistent_references_are_dropped(self) -> None:
        # Overlapping layers where the third contradicts the first two.
        att = np.array([1000.0, 2000.0, 1500.0])
        limits = np.array([2000.0, 2000.0, 1000.0])
        el = np.array([600.0, 350.0, 900.0])
        strict = _calculate_layer_losses(att, limits, el, overlapping=True)
        assert strict.status == 4
        tower = _calculate_layer_losses(
            att, limits, el, overlapping=True, ignore_inconsistent_references=True
        )
        assert tower.status == 1
        assert np.all(np.isfinite(tower.exp_loss))
        # The kept layers (first two) are still matched.
        assert tower.exp_loss[tower.att < 3000.0].sum() == pytest.approx(600.0)

    def test_drop_order_follows_sorted_layers(self) -> None:
        # Unsorted input: after sorting, 1000 is kept first and 2000 is dropped.
        att = np.array([2000.0, 1000.0, 3000.0])
        limits = np.array([1000.0, 1000.0, 1000.0])
        el = np.array([150.0, 100.0, 20.0])
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            tower = _calculate_layer_losses(att, limits, el, ignore_inconsistent_references=True)
        assert tower.status == 1
        assert tower.exp_loss[tower.att == 1000.0][0] == pytest.approx(100.0)
        assert tower.exp_loss[tower.att == 3000.0][0] == pytest.approx(20.0)
